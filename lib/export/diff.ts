export type DiffDocumentInput = {
  title: Pick<Title, "name_zh" | "name_en" | "external_id" | "genre">;
  episode: Pick<Episode, "number" | "name_zh" | "name_en" | "external_id">;
  snapshot: VersionSnapshot;
  locale: DocLocale;
  /**
   * The version row the snapshot came from; without it the header says
   * "draft" and prints no hash (a draft export before submit).
   */
  version?: {
    status: VersionStatus;
    snapshot_sha256: string | null;
    submitted_at?: string | null;
    approved_at?: string | null;
    approval_mode?: ApprovalMode | null;
  } | null;
  /** Shown in the header when known (the snapshot carries only the producer uuid). */
  producer_name?: string | null;
};

const fill = (s: string, n: number) => s.replace("{n}", String(n));

function statusTone(s: VersionStatus): "neutral" | "accent" | "success" | "warning" {
  return s === "approved" ? "success" : s === "in_review" ? "accent" : s === "draft" ? "warning" : "neutral";
}

type Joined = { adapted: SnapshotAdaptedLine; anchor: SnapshotLine | null; merged: SnapshotLine[] };

/** Adapted lines joined to their source lines; unadapted source lines come back separately, in seq order. */
function joinScene(scene: SnapshotScene): { joined: Joined[]; orphans: SnapshotLine[] } {
  const src = new Map(scene.lines.map((l) => [l.id, l]));
  const covered = new Set<string>();
  const joined = scene.adapted_lines.map((a) => {
    const anchor = a.line_id ? src.get(a.line_id) ?? null : null;
    if (anchor) covered.add(anchor.id);
    const merged = a.merges.flatMap((id) => {
      const m = src.get(id);
      if (m) covered.add(m.id);
      return m ? [m] : [];
    });
    return { adapted: a, anchor, merged };
  });
  const orphans = scene.lines.filter((l) => !covered.has(l.id));
  return { joined, orphans };
}

function tagPills(a: SnapshotAdaptedLine, locale: DocLocale): string {
  return a.tags
    .map((t) => TAG_LABELS[t])
    .filter(Boolean)
    .map((l) => pill(locale === "zh" ? l.zh : l.en, "neutral"))
    .join("");
}

function lineBlock(j: Joined, locale: DocLocale, sceneNumber?: number): string {
  const L = LABELS[locale];
  const a = j.adapted;
  const zh = [j.anchor?.text_zh ?? "", ...j.merged.map((m) => m.text_zh)].filter(Boolean).join(" ");
  const at = clockTime(a.start_ms ?? j.anchor?.start_ms);
  const who = j.anchor?.speaker;
  const why = locale === "zh" ? a.rationale_zh ?? a.rationale_en : a.rationale_en ?? a.rationale_zh;
  const tone = locale === "zh" ? a.tone_note_zh ?? a.tone_note_en : a.tone_note_en ?? a.tone_note_zh;
  const isCut = a.change_type === "cut" || a.text_en === null;
  const flags = [
    a.is_major ? pill(L.majorFlag, "error") : "",
    pill(L.change[a.change_type] ?? a.change_type, a.is_major ? "warning" : "neutral"),
    tagPills(a, locale),
  ].join("");
  const ref = sceneNumber !== undefined ? `<span class="faint micro"> · ${esc(fill(L.scene, sceneNumber))}</span>` : "";

  return `<div class="line${a.is_major ? " major" : ""}" id="${esc(a.external_id)}">
  <div class="at">${esc(at)}<br><span class="mono micro">${esc(a.external_id)}</span></div>
  <div>
    ${who ? `<div class="who">${esc(who)}${ref}</div>` : ref ? `<div class="who">${ref}</div>` : ""}
    <div class="zh"><span class="label">${esc(L.source)}</span><br>${esc(zh)}</div>
    ${
      isCut
        ? `<div class="cut">${esc(L.cut)}</div>`
        : `<div class="bt"><span class="label">${esc(L.back)}</span><br>${esc(a.back_translation_zh ?? "")}</div>
    <div class="en"><span class="label">${esc(L.english)}</span> ${esc(a.text_en)}</div>`
    }
    <div class="flags">${flags}</div>
    ${why ? `<div class="why"><b>${esc(L.why)}</b> ${esc(why)}</div>` : ""}
    ${tone ? `<div class="why"><b>${esc(L.tone)}</b> ${esc(tone)}</div>` : ""}
  </div>
</div>`;
}

function orphanBlock(l: SnapshotLine, locale: DocLocale): string {
  const L = LABELS[locale];
  return `<div class="line" id="${esc(l.external_id)}">
  <div class="at">${esc(clockTime(l.start_ms))}<br><span class="mono micro">${esc(l.external_id)}</span></div>
  <div>
    ${l.speaker ? `<div class="who">${esc(l.speaker)}</div>` : ""}
    <div class="zh"><span class="label">${esc(L.source)}</span><br>${esc(l.text_zh)}</div>
    <div class="flags">${pill(L.unadapted, "warning")}</div>
  </div>
</div>`;
}

function sceneSection(scene: SnapshotScene, locale: DocLocale): string {
  const L = LABELS[locale];
  const { joined, orphans } = joinScene(scene);
  // Interleave by seq so an unadapted source line sits where it belongs in the script.
  const entries: Array<{ seq: number; html: string }> = [
    ...joined.map((j) => ({ seq: j.adapted.seq, html: lineBlock(j, locale) })),
    ...orphans.map((l) => ({ seq: l.seq, html: orphanBlock(l, locale) })),
  ].sort((a, b) => a.seq - b.seq);
  const context = locale === "zh" ? scene.context_zh ?? scene.context_en : scene.context_en ?? scene.context_zh;
  const range = clockRange(scene.start_ms, scene.end_ms);
  return `<section class="scene" id="${esc(scene.external_id)}">
  <div class="scene-head"><h3>${esc(fill(L.scene, scene.number))}</h3>${range ? `<span class="small faint">${esc(range)}</span>` : ""}<span class="mono micro faint">${esc(scene.external_id)}</span></div>
  ${context ? `<div class="context"><span class="label">${esc(L.context)}</span><br>${escMultiline(context)}</div>` : ""}
  ${entries.map((e) => e.html).join("\n")}
</section>`;
}

export function diffDocumentHtml(i: DiffDocumentInput): string {
  const L = LABELS[i.locale];
  const s = i.snapshot;
  const status: VersionStatus = i.version?.status ?? "draft";
  const nameZh = i.title.name_zh || s.title.name_zh;
  const nameEn = s.version.display_title_en ?? i.title.name_en ?? s.title.name_en;
  const epName = i.locale === "zh" ? i.episode.name_zh ?? i.episode.name_en : i.episode.name_en ?? i.episode.name_zh;
  const heading = i.locale === "zh" ? nameZh : nameEn ?? nameZh;
  const subheading = i.locale === "zh" ? nameEn : nameZh;

  const allLines = s.scenes.flatMap((sc) => sc.lines);
  const allAdapted = s.scenes.flatMap((sc) => sc.adapted_lines);
  const changed = allAdapted.filter((a) => a.change_type !== "keep" && a.change_type !== "literal").length;
  const majors = s.scenes.flatMap((sc) =>
    joinScene(sc).joined.filter((j) => j.adapted.is_major).map((j) => ({ j, scene: sc.number })),
  );

  const approvalLine =
    status === "approved"
      ? i.version?.approval_mode === "on_behalf"
        ? L.approvedOnBehalf
        : L.approved
      : null;

  const meta = metaList([
    [L.versionId, s.version.external_id],
    [L.sha, i.version?.snapshot_sha256 ?? null],
    [L.submitted, fmtDate(i.version?.submitted_at, i.locale)],
    [approvalLine ?? L.approved, status === "approved" ? fmtDate(i.version?.approved_at, i.locale) || "—" : null],
    [L.producer, i.producer_name ?? null],
    [L.target, s.version.target_locale],
    [L.scenes, String(s.scenes.length)],
    [L.lines, String(allLines.length)],
    [L.changed, String(changed)],
  ]);

  const body = `<header class="head">
  <div>
    <div class="label">${esc(L.doc)}</div>
    <h1>${esc(heading)}</h1>
    ${subheading ? `<div class="sub muted">${esc(subheading)}</div>` : ""}
    <div class="sub">${esc(fill(L.episode, i.episode.number))}${epName ? ` · ${esc(epName)}` : ""} · ${esc(L.version)} ${s.version.number}</div>
  </div>
  <div>${pill(L.status[status], statusTone(status))}</div>
</header>
${meta}

<h2>${esc(L.major)}</h2>
<p class="small muted">${esc(L.majorIntro)}</p>
${majors.length ? majors.map(({ j, scene }) => lineBlock(j, i.locale, scene)).join("\n") : `<p class="small faint" style="margin-top:8px">${esc(L.majorNone)}</p>`}

${s.scenes.map((sc) => sceneSection(sc, i.locale)).join("\n")}

<footer class="foot">${esc(L.foot)}</footer>`;

  return docShell({
    lang: i.locale,
    title: `${heading} · ${fill(L.episode, i.episode.number)} · ${L.doc}`,
    body,
  });
}
