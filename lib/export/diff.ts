// The bilingual diff document: the file the producer (制片方) reads, signs off
// on and keeps. It renders from the frozen snapshot only, so the same
// version always prints the same pages, and the header names the version
// (ver_ id + sha256 + approval state) so a printout can be matched to the
// row it came from. Major changes lead, because that is what the partner
// reviews first; then every scene, one per printed page, each line as a
// three-part block: the Chinese source, the Chinese back-translation the
// partner actually judges (set larger, tinted), and the English underneath,
// small, with 为什么这样改编 and the tone shift.
//
// Chrome strings live in LABELS below in both languages: this is a
// generated file, not the app, so it does not go through the dictionaries.

